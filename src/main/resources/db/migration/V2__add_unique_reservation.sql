-- 2-1단계 ①: 중복 예약을 막는 DB 최후 방어선.
--
-- 같은 지원자가 같은 슬롯에 예약 행을 두 번 만드는 것(더블클릭·재시도·레이스)을 DB 레벨에서
-- 원천 차단한다. 애플리케이션 코드에 버그가 있어도 이 제약이 있으면 중복 행 자체가 만들어질
-- 수 없다 — "최후 방어선"이라 부르는 이유다.
--
-- 왜 baseline 재현을 깨지 않는가:
--   * baseline 오버부킹은 *서로 다른* 지원자들이 한 슬롯의 마지막 자리를 두고 경쟁하는 것이다.
--     (지원자, 슬롯) 쌍이 서로 다르므로 이 UNIQUE 는 그 경쟁을 건드리지 않는다.
--   * BaselineOverbookingProbeTest 는 라운드마다 새 슬롯을 만들어 (지원자, 슬롯) 쌍이 늘 유일하다.
--   * Gatling 시나리오도 한 슬롯에 서로 다른 지원자 N명을 붙인다.
--   따라서 이 제약은 전역으로 걸어도 1단계 재현 자산과 충돌하지 않는다.
--
-- 이 제약이 다루는 문제(같은 사용자의 중복 요청)와 오버부킹(정원 경쟁)은 서로 다른 문제다.
-- UNIQUE 는 전자만 막는다 — 오버부킹 방지는 ②(조건부 UPDATE) 이후 몫이다.

ALTER TABLE reservation
    ADD CONSTRAINT uk_reservation_applicant_slot UNIQUE (applicant_id, slot_id);
